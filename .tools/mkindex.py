# -*- coding: utf-8 -*-
import re, glob, os
SRC='/workspace/.extract/txt'; DST='/workspace/docs/requirements/by_bp/enriched'
rows=[]; tot=0
for src in sorted(glob.glob(os.path.join(SRC,'*.txt'))):
    name=re.sub(r'\.md$','',os.path.basename(src)[:-4])
    raw=open(src,encoding='utf-8',errors='replace').read(); tot+=len(raw)
    dst=os.path.join(DST,name+'.md')
    ok = '✅' if os.path.exists(dst) else '❌'
    words=len(re.findall(r'\S+',raw))
    rows.append(f"| {ok} | [{name}](enriched/{name}.md) | {len(raw):,} | {words:,} |".replace(',',' '))
idx = ["# INDEX — обогащённые карточки требований по каждой БП (по Вигерсу)\n",
"Каждая карточка `enriched/<БП>.md` состоит из трёх слоёв:",
"- **Слой А** — структурированная карточка: термины → подсистемы → компоненты → цель → бизнес-цели/процессы → пользовательские требования (УТ/User Stories, дословно) → функции системы (ФС) → раздел 5 целиком → варианты использования → сценарии/алгоритмы → функции (п.8) → данные (п.9) → внешние системы (п.10) → прочие задачи (п.11) → критерии приёмки (п.12) → внутренние вопросы/неясности → особенности структуры источника;",
"- **Слой B** — артефакты вне нумерованных разделов и нестандартные разделы (>12), дословно;",
"- **Слой C** — полный оригинал без сокращений (гарантия «не потерять ни буквы»); верифицировано автоматической проверкой вхождения нормализованного оригинала в файл карточки — 68/68 OK.\n",
"Где таблица п.5 заполнена нестандартно, УТ извлечены поиском формулировок «Пользователь должен / Необходимо обеспечить / Система должна / Требуется» по всему тексту и помечены ⚠️.",
f"\nВсего БП: **{len(rows)}**; суммарный объём оригиналов: **{tot:,} симв.**\n".replace(',',' '),
"| ✓ | Бизнес-постановка | Символов | Слов |","|---|---|---|---|"]
open(os.path.join(os.path.dirname(DST),'INDEX.md'),'w').write('\n'.join(idx+rows)+'\n')
print('index rows:', len(rows))
